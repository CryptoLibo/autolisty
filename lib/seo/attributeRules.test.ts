import { describe, expect, it } from "vitest"
import { shouldGenerateEtsyAttribute } from "./attributeRules"

describe("Etsy attributes generated by the AI", () => {
  it("cubre colores, room, estilo, subject y festividad en wall art y Frame TV", () => {
    for (const name of ["Primary color", "Secondary color", "Room", "Home style", "Art subject", "Holiday", "Occasion"]) {
      expect(shouldGenerateEtsyAttribute("frame_tv_art", name)).toBe(true)
    }
    expect(shouldGenerateEtsyAttribute("frame_tv_art", "Orientation")).toBe(false)
    // Archivo digital sin marco: Frame color no aplica.
    expect(shouldGenerateEtsyAttribute("frame_tv_art", "Frame color")).toBe(false)
  })

  it("respeta lo fijo de cada producto", () => {
    expect(shouldGenerateEtsyAttribute("nursery_wall_art", "Room")).toBe(false)
    expect(shouldGenerateEtsyAttribute("png_designs", "Primary color")).toBe(false)
    expect(shouldGenerateEtsyAttribute("png_designs", "Holiday")).toBe(true)
  })
})
